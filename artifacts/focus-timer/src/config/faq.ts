// Генерация FAQPage structured data
export function generateFAQStructuredData(pageKey: string) {
  const faqs = faqData[pageKey] || faqData.home;
  
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    "mainEntity": faqs.map(faq => ({
      "@type": "Question",
      "name": faq.question,
      "acceptedAnswer": {
        "@type": "Answer",
        "text": faq.answer
      }
    }))
  };
}
